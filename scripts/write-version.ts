// Writes src/version.ts from package.json's version. Runs as the `version` lifecycle script, so
// `npm version` / `yarn version` keep the two together; tests/version.test.ts fails when they differ.
import { readFile, writeFile } from "node:fs/promises";
import { z } from "zod";

const { version } = z.object({ version: z.string() }).parse(JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8")));
const text = `// Generated by scripts/write-version.ts from package.json (run by \`npm version\` / \`yarn version\`) — do not edit.
// The package's version, for the CLI's --version, the MCP server's handshake and the browser
// loader's default CDN URL; a constant, so the browser entry needs no file read.
export const PACKAGE_VERSION = ${JSON.stringify(version)};

export function packageVersion(): string {
  return PACKAGE_VERSION;
}
`;
await writeFile(new URL("../src/version.ts", import.meta.url), text);
console.log(`wrote src/version.ts (${version})`);
